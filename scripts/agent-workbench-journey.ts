import { expect } from '@rstest/playwright';
import type { Page } from 'playwright';

export async function verifyAgentWorkbench(page: Page) {
  const result = page.getByLabel('Tool result').locator('pre');
  const review = page.getByRole('radiogroup', { name: 'Review confidence', exact: true });
  const approval = page.getByRole('radiogroup', { name: 'Approval level', exact: true });
  await expect(page.getByRole('status', { name: 'Agent status' })).toHaveText('Agent access is off.');
  await expect(review).toHaveCount(0);
  await page.getByRole('button', { name: 'Enable local agent', exact: true }).click();
  const human = page.getByRole('textbox', { name: 'Human project name' });
  await human.fill('Human-owned project');
  await page.getByRole('button', { name: 'Fill sample', exact: true }).click();
  await expect(review.getByRole('radio', { name: '4 of 5 stars' })).toBeChecked();
  await page.getByRole('button', { name: 'Try refused value' }).click();
  await expect(review.getByRole('radio', { name: '4 of 5 stars' })).toBeChecked();
  await page.getByRole('button', { name: 'Try Base UI edit' }).click();
  await expect(human).toHaveValue('Human-owned project');
  await page.getByRole('button', { name: 'Inspect UI', exact: true }).click();
  await expect(result).toContainText('Review confidence');
  await expect(result).toContainText('[redacted]');
  await expect(result).not.toContainText('Human-owned project');
  await expect(result).not.toContainText('Private score');
  await page.getByRole('button', { name: 'Fill secret' }).click();
  await expect(
    page.getByRole('radiogroup', { name: 'Secret score', exact: true }).getByRole('radio', { name: '3 of 5 stars' })
  ).toBeChecked();
  await page.getByRole('button', { name: 'Ask agent to approve' }).click();
  const dialog = page.getByRole('dialog', { name: 'Approve agent action' });
  await expect(dialog).toBeVisible();
  await dialog.getByRole('button', { name: 'Reject action', exact: true }).click();
  await expect(approval.getByRole('radio', { checked: true })).toHaveCount(0);
  await page.getByRole('button', { name: 'Ask agent to approve' }).click();
  await dialog.getByRole('button', { name: 'Approve action', exact: true }).click();
  await expect(approval.getByRole('radio', { name: '3 of 5 stars' })).toBeChecked();
  await page.getByRole('button', { name: 'Save local record', exact: true }).click();
  const saved = page.getByLabel('Saved local record');
  await expect(saved).toHaveText('{"confidence":4,"approval":3}');
  await page.getByRole('button', { name: 'Seek to start' }).click();
  await dialog.getByRole('button', { name: 'Approve action', exact: true }).click();
  await expect(review.getByRole('radio', { name: '2 of 5 stars' })).toBeChecked();
  await page.getByRole('button', { name: 'Replay history' }).click();
  await dialog.getByRole('button', { name: 'Approve action', exact: true }).click();
  await expect(review.getByRole('radio', { name: '4 of 5 stars' })).toBeChecked();
  await page.getByRole('button', { name: 'Preview suggestion' }).click();
  await expect(review.getByRole('radio', { name: '3 of 5 stars' })).toBeChecked();
  await page.getByRole('button', { name: 'Revert preview' }).click();
  await expect(review.getByRole('radio', { name: '4 of 5 stars' })).toBeChecked();
  await review.getByRole('radio', { name: '4 of 5 stars' }).press('Home');
  await expect(review.getByRole('radio', { name: '1 of 5 stars' })).toBeChecked();
  await page.getByRole('button', { name: 'Undo agent edits' }).click();
  await dialog.getByRole('button', { name: 'Approve action', exact: true }).click();
  await expect(review.getByRole('radio', { name: '1 of 5 stars' })).toBeChecked();
  await expect(saved).toHaveText('{"confidence":4,"approval":3}');
  await page.getByRole('button', { name: 'Inspect tool schemas' }).click();
  await expect(result).toContainText('inputSchema');
  await expect(result).toContainText('snapshot');
  await page.getByRole('button', { name: 'Ask agent to approve' }).click();
  await expect(dialog).toBeVisible();
  await dialog.getByRole('button', { name: 'Stop agent', exact: true }).click();
  await expect(dialog).toHaveCount(0);
  await expect(review).toHaveCount(0);
  await expect(result).toHaveText('Agent access is off.');
  await page.getByRole('button', { name: 'Enable local agent', exact: true }).click();
  await page.getByRole('button', { name: 'Fill sample', exact: true }).click();
  await expect(review.getByRole('radio', { name: '4 of 5 stars' })).toBeChecked();
  await page.getByRole('button', { name: 'Disable agent', exact: true }).click();
  await expect(review).toHaveCount(0);
  await expect(page.getByRole('button', { name: 'Fill sample', exact: true })).toBeDisabled();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
}
