import { expect } from '@rstest/playwright';
import type { Page } from 'playwright';

const titleName = /^Title/u;
const regionName = /^Region/u;
export async function verifyUIFoundations(page: Page) {
  const base = page.getByRole('region', { name: 'Base UI form', exact: true });
  const title = base.getByRole('textbox', { name: titleName });
  await expect(page.getByRole('radiogroup', { name: 'SDK rating' })).toHaveCount(0);
  await expect(page.getByLabel('SDK status', { exact: true })).toHaveText('SDK disabled');
  await title.fill('');
  await base.getByRole('button', { name: 'Submit', exact: true }).click();
  await expect(base.getByText('Enter a title', { exact: true })).toBeVisible();
  await title.fill('Saved Base UI project 🌊');
  await base.getByRole('combobox', { name: regionName }).click();
  await page.getByRole('option', { name: 'North America', exact: true }).click();
  await page.getByRole('button', { name: 'Enable SDK enhancement', exact: true }).click();
  await page.getByRole('button', { name: 'Set SDK rating through agent', exact: true }).click();
  await expect(page.getByLabel('SDK score', { exact: true })).toHaveText('4');
  await page.getByRole('button', { name: 'Inspect SDK snapshot', exact: true }).click();
  await expect(page.getByLabel('SDK snapshot', { exact: true })).toContainText('SDK rating');
  await expect(page.getByLabel('SDK snapshot', { exact: true })).not.toContainText('Saved Base UI project');
  await page.getByRole('button', { name: 'Try agent edit on Base UI', exact: true }).click();
  await expect(page.getByLabel('SDK status', { exact: true })).toHaveText('SDK refused');
  await expect(title).toHaveValue('Saved Base UI project 🌊');
  await base.getByRole('button', { name: 'Submit', exact: true }).click();
  const saved = page.getByLabel('Saved Base UI values', { exact: true });
  await expect(saved).toContainText('Saved Base UI project 🌊');
  await expect(saved).toContainText('"region":"us"');
  await page.getByRole('button', { name: 'Undo SDK agent changes', exact: true }).click();
  await expect(page.getByLabel('SDK score', { exact: true })).toHaveText('0');
  await expect(saved).toContainText('"region":"us"');
  await expect(title).toHaveValue('Saved Base UI project 🌊');
  await page.getByRole('button', { name: 'Stop SDK enhancement', exact: true }).click();
  await expect(page.getByRole('radiogroup', { name: 'SDK rating' })).toHaveCount(0);
  await expect(page.getByRole('button', { name: 'Set SDK rating through agent', exact: true })).toBeDisabled();
  await page.getByRole('button', { name: 'Enable SDK enhancement', exact: true }).click();
  await page.getByRole('button', { name: 'Set SDK rating through agent', exact: true }).click();
  await expect(page.getByLabel('SDK score', { exact: true })).toHaveText('4');
  await page.getByRole('button', { name: 'Stop SDK enhancement', exact: true }).click();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
}
